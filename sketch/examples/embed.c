/*
 * embed.c: calling the same App from C (and therefore Swift, Go, Rust,
 * Dart/Flutter FFI, Python ctypes, ...).
 *
 *   cc embed.c -Izig-out/include -Lzig-out/lib -lsupport -o embed
 *
 * The C ABI is deliberately JSON-at-the-edges: inputs and outputs cross the
 * boundary as UTF-8 JSON validated against the comptime-generated schemas, so
 * one small, stable header serves every agent and workflow. Zig callers never
 * pay this cost; they use the typed API directly.
 *
 * Streaming is pull-based, the same shape as Zig's `stream.next()`: no
 * callbacks, no reentrancy rules. A pending approval just means `next` stops
 * making progress until you `respond`. If a human will take a while, save the
 * run with `zastra_stream_suspend` and resume it later, from any process
 * with the same storage, with `support_agent_resume`.
 */
#include <stdio.h>
#include <string.h>
#include "support.h" /* generated by `zig build lib` */

/* Copy the string value of "key" out of a flat JSON object (enough for ids). */
static int json_str(const char *json, const char *key, char *out, size_t n) {
    char pat[64];
    snprintf(pat, sizeof pat, "\"%s\":\"", key);
    const char *p = strstr(json, pat);
    if (!p) return 0;
    p += strlen(pat);
    size_t i = 0;
    while (p[i] && p[i] != '"' && i + 1 < n) { out[i] = p[i]; i++; }
    out[i] = 0;
    return 1;
}

int main(void) {
    zastra_error err = {0};

    /* Config is JSON too; NULL fields fall back to env vars. */
    zastra_app *app = support_app_new("{\"storage\":{\"sqlite\":\"z.sqlite\"}}", &err);
    if (!app) {
        fprintf(stderr, "init failed: %s\n", err.message); /* e.g. missing ANTHROPIC_API_KEY */
        return 1;
    }

    /* IDs are generated constants, so a typo is a compile error in C too. */
    zastra_stream *s = support_agent_stream(app, SUPPORT_AGENT_SUPPORT,
        "Please refund ORD-1042, it was broken.",
        "{\"thread\":\"ticket-8812\",\"resource\":\"customer-42\"}",
        &err);
    if (!s) {
        fprintf(stderr, "stream failed: %s\n", err.message);
        support_app_free(app);
        return 1;
    }

    /* Events are the same tagged union as in Zig, flattened to a kind plus a
     * JSON payload. Pointers in `ev` stay valid until the next `next` call. */
    zastra_event ev;
    zastra_status st;
    while ((st = zastra_stream_next(s, &ev)) == ZASTRA_OK) {
        switch (ev.kind) {
        case ZASTRA_EVENT_TEXT_DELTA:
            fwrite(ev.json, 1, ev.len, stdout); /* raw text, not JSON, for deltas */
            break;
        case ZASTRA_EVENT_APPROVAL_REQUEST:
            /* Could respond right here with zastra_stream_respond(s, ev.approval_id,
             * "{\"approve\":true}", &err). Instead, let a human decide later. */
            fprintf(stderr, "\n[approval needed] %.*s\n", (int)ev.len, ev.json);
            break;
        default:
            break;
        }
    }
    char run_id[96] = {0}, approval_id[96] = {0};
    if (st == ZASTRA_ERR_APPROVAL_PENDING) {
        /* {"status":"suspended","run_id":"run_...","requests":[{"id":"toolu_...","tool":"issue_refund","input":{...}}]} */
        zastra_result *saved = zastra_stream_suspend(s, &err);
        if (saved) {
            printf("\nsaved: %s\n", zastra_result_json(saved));
            json_str(zastra_result_json(saved), "run_id", run_id, sizeof run_id);
            json_str(zastra_result_json(saved), "id", approval_id, sizeof approval_id);
        } else fprintf(stderr, "suspend failed: %s\n", err.message);
        zastra_result_free(saved);
    } else if (st != ZASTRA_DONE) fprintf(stderr, "stream ended (%d): %s\n", (int)st, zastra_stream_error(s));
    zastra_stream_free(s); /* also cancels the run if it is still going */

    if (run_id[0]) {
        /* Hours later, possibly in another process: decide and continue. */
        char decisions[256];
        snprintf(decisions, sizeof decisions, "[{\"id\":\"%s\",\"deny\":\"Over limit; escalate.\"}]", approval_id);
        zastra_result *done = support_agent_resume(app, SUPPORT_AGENT_SUPPORT, run_id, decisions, &err);
        printf("resumed: %s\n", done ? zastra_result_json(done) : err.message);
        zastra_result_free(done);
    }

    /* Typed output, as JSON matching SUPPORT_TRIAGE_SCHEMA. */
    zastra_result *r = support_agent_generate(app, SUPPORT_AGENT_TRIAGE,
        "My order ORD-1042 arrived smashed!", NULL, &err);
    if (r) printf("\ntriage: %s\n", zastra_result_json(r));
    zastra_result_free(r);

    /* Workflows: start can return {"status":"suspended","run_id":...,"at":"refunder","payload":{"requests":[...]}};
     * resume with support_workflow_resume(app, run_id, "refunder", "{\"approve\":[\"<request id>\"]}", &err). */
    r = support_workflow_start(app, SUPPORT_WORKFLOW_HANDLE_TICKET,
        "{\"customer_id\":\"customer-42\",\"subject\":\"Broken\",\"body\":\"ORD-1042 cracked\"}",
        &err);
    printf("workflow: %s\n", r ? zastra_result_json(r) : err.message);
    zastra_result_free(r);

    support_app_free(app);
    return 0;
}
