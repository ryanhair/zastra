//! C header generation for `z.addCLib` (PLAN.md §9).

const std = @import("std");
const reflect = @import("../meta/reflect.zig");
const json_schema = @import("../schema/json_schema.zig");
const manifest = @import("manifest.zig");
const step = @import("../workflow/step.zig");

pub const abi_version: u32 = 2;

fn cString(comptime s: []const u8) []const u8 {
    comptime {
        var out: []const u8 = "\"";
        for (s) |c| out = out ++ switch (c) {
            '"' => "\\\"",
            '\\' => "\\\\",
            '\n' => "\\n",
            '?' => "\\?", // avoid trigraphs
            else => &[_]u8{c},
        };
        return out ++ "\"";
    }
}

pub fn render(comptime App: type, comptime lib: []const u8) []const u8 {
    comptime {
        @setEvalBranchQuota(50_000_000);
        const L = reflect.upperSnake(lib);
        var h: []const u8 =
            "/* " ++ lib ++ ".h: generated by zastra (z.addCLib). Do not edit. */\n" ++
            "#ifndef " ++ L ++ "_H\n#define " ++ L ++ "_H\n\n" ++
            "#include <stddef.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n" ++
            std.fmt.comptimePrint("#define ZASTRA_ABI_VERSION {d}u\n", .{abi_version}) ++
            std.fmt.comptimePrint("#define {s}_MANIFEST_FINGERPRINT 0x{x:0>16}ull\n\n", .{ L, manifest.fingerprint(App) }) ++
            \\#ifndef ZASTRA_COMMON_TYPES
            \\#define ZASTRA_COMMON_TYPES
            \\typedef struct zastra_app zastra_app;
            \\typedef struct zastra_stream zastra_stream;
            \\typedef struct zastra_result zastra_result;
            \\
            \\typedef struct zastra_error {
            \\    int code;
            \\    char message[512];
            \\} zastra_error;
            \\
            \\typedef enum zastra_status {
            \\    ZASTRA_OK = 0,
            \\    ZASTRA_DONE = 1,
            \\    ZASTRA_ERR = -1,
            \\    ZASTRA_ERR_APPROVAL_PENDING = -2,
            \\    ZASTRA_ERR_CANCELED = -3,
            \\    ZASTRA_ERR_INVALID_INPUT = -4,
            \\    ZASTRA_ERR_ABI_MISMATCH = -6
            \\} zastra_status;
            \\
            \\typedef enum zastra_event_kind {
            \\    ZASTRA_EVENT_TEXT_DELTA = 0,
            \\    ZASTRA_EVENT_REASONING_DELTA = 1,
            \\    ZASTRA_EVENT_TOOL_CALL = 2,
            \\    ZASTRA_EVENT_TOOL_RESULT = 3,
            \\    ZASTRA_EVENT_APPROVAL_REQUEST = 4,
            \\    ZASTRA_EVENT_STEP_FINISH = 5,
            \\    ZASTRA_EVENT_FINISH = 6,
            \\    /* `.partial_output = true` agents: the output so far (unvalidated), and
            \\     * a marker that earlier partial values were discarded (a repair). */
            \\    ZASTRA_EVENT_OUTPUT_PARTIAL = 7,
            \\    ZASTRA_EVENT_OUTPUT_PARTIAL_RESET = 8
            \\} zastra_event_kind;
            \\
            \\/* Pointers stay valid until the next zastra_stream_next() on the same stream.
            \\ * For TEXT_DELTA and REASONING_DELTA, `json` is raw text; otherwise JSON. */
            \\typedef struct zastra_event {
            \\    zastra_event_kind kind;
            \\    const char *json;
            \\    size_t len;
            \\    const char *approval_id; /* APPROVAL_REQUEST only, else NULL */
            \\} zastra_event;
            \\
            \\uint32_t zastra_abi_version(void);
            \\
            \\/* Pull-based streaming (PLAN.md D14). While an approval is pending, next()
            \\ * returns ZASTRA_ERR_APPROVAL_PENDING without blocking. */
            \\zastra_status zastra_stream_next(zastra_stream *s, zastra_event *out);
            \\/* decision_json: {"approve":true} or {"deny":"reason"} */
            \\zastra_status zastra_stream_respond(zastra_stream *s, const char *approval_id, const char *decision_json, zastra_error *err);
            \\/* Safe from any thread. */
            \\void zastra_stream_cancel(zastra_stream *s);
            \\/* While next() returns ZASTRA_ERR_APPROVAL_PENDING: save the run and stop.
            \\ * Returns {"status":"suspended","run_id":...,"requests":[...]}; resume it later
            \\ * with <lib>_agent_resume or <lib>_agent_resume_stream (caller frees). */
            \\zastra_result *zastra_stream_suspend(zastra_stream *s, zastra_error *err);
            \\/* After ZASTRA_DONE: the collected result (caller frees). */
            \\zastra_result *zastra_stream_result(zastra_stream *s, zastra_error *err);
            \\/* Why the last zastra_stream_next() returned an error ("" if it didn't). */
            \\const char *zastra_stream_error(zastra_stream *s);
            \\void zastra_stream_free(zastra_stream *s);
            \\
            \\const char *zastra_result_json(const zastra_result *r);
            \\void zastra_result_free(zastra_result *r);
            \\#endif /* ZASTRA_COMMON_TYPES */
            \\
            \\
            ;

        // IDs
        h = h ++ "/* Agents */\n";
        for (App.agents, 0..) |A, i| h = h ++ std.fmt.comptimePrint("#define {s}_AGENT_{s} {d}\n", .{ L, reflect.upperSnake(A.id), i });
        h = h ++ "\n/* Workflows */\n";
        for (App.workflows, 0..) |W, i| h = h ++ std.fmt.comptimePrint("#define {s}_WORKFLOW_{s} {d}\n", .{ L, reflect.upperSnake(W.id), i });

        // Schemas for the types that cross the boundary.
        h = h ++ "\n/* JSON Schemas for inputs and outputs */\n";
        var seen: []const []const u8 = &.{};
        for (App.agents) |A| if (A.has_output_type) {
            const name = reflect.upperSnake(reflect.snakeCase(reflect.shortTypeName(A.Output)));
            if (!contains(seen, name)) {
                seen = seen ++ &[_][]const u8{name};
                h = h ++ "#define " ++ L ++ "_" ++ name ++ "_SCHEMA " ++ cString(json_schema.of(A.Output)) ++ "\n";
            }
        };
        for (App.workflows) |W| {
            for ([_]type{ W.Input, W.Output }) |T| {
                const name = reflect.upperSnake(reflect.snakeCase(reflect.shortTypeName(T)));
                if (!contains(seen, name)) {
                    seen = seen ++ &[_][]const u8{name};
                    h = h ++ "#define " ++ L ++ "_" ++ name ++ "_SCHEMA " ++ cString(json_schema.of(T)) ++ "\n";
                }
            }
            for (W.suspendable_steps) |S| {
                const name = reflect.upperSnake(step.idOf(S)) ++ "_RESUME";
                h = h ++ "#define " ++ L ++ "_" ++ name ++ "_SCHEMA " ++ cString(json_schema.of(S.Resume)) ++ "\n";
            }
        }

        h = h ++ "\n/* The App */\n" ++
            "zastra_app *" ++ lib ++ "_app_new_checked(const char *config_json, uint64_t manifest_fingerprint, zastra_error *err);\n" ++
            "/* config_json: {\"storage\":{\"sqlite\":\"path\"},\"env\":{\"ANTHROPIC_API_KEY\":\"...\"},\"trace\":\"file.jsonl\"}; NULL fields fall back to env vars.\n" ++
            " * Fails with ZASTRA_ERR_ABI_MISMATCH if this header doesn't match the library. */\n" ++
            "#define " ++ lib ++ "_app_new(config_json, err) " ++ lib ++ "_app_new_checked((config_json), " ++ L ++ "_MANIFEST_FINGERPRINT, (err))\n" ++
            "void " ++ lib ++ "_app_free(zastra_app *app);\n\n" ++
            "/* input: plain text, or a JSON array of messages. opts_json: {\"thread\",\"resource\",\"max_steps\"} or NULL. */\n" ++
            "/* Results: {\"status\":\"completed\",\"text\",\"output\",\"steps\",\"finish_reason\",\"run_id\",\"usage\"}, or for agents with\n" ++
            " * approval-gated tools {\"status\":\"suspended\",\"run_id\",\"requests\":[{\"id\",\"tool\",\"input\"}]} (the run is saved). */\n" ++
            "zastra_result *" ++ lib ++ "_agent_generate(zastra_app *app, int agent_id, const char *input, const char *opts_json, zastra_error *err);\n" ++
            "zastra_stream *" ++ lib ++ "_agent_stream(zastra_app *app, int agent_id, const char *input, const char *opts_json, zastra_error *err);\n" ++
            "/* decisions_json: [{\"id\":\"...\",\"approve\":true}, {\"id\":\"...\",\"deny\":\"reason\"}]. Undecided requests keep the run suspended. */\n" ++
            "zastra_result *" ++ lib ++ "_agent_resume(zastra_app *app, int agent_id, const char *run_id, const char *decisions_json, zastra_error *err);\n" ++
            "zastra_stream *" ++ lib ++ "_agent_resume_stream(zastra_app *app, int agent_id, const char *run_id, const char *decisions_json, zastra_error *err);\n" ++
            "/* Abandon a suspended run. */\n" ++
            "zastra_status " ++ lib ++ "_agent_cancel(zastra_app *app, int agent_id, const char *run_id, zastra_error *err);\n\n" ++
            "/* Results: {\"status\":\"completed\",\"output\":...} | {\"status\":\"suspended\",\"run_id\",\"at\",\"payload\"} | {\"status\":\"failed\",\"step\",\"error\",\"message\"} */\n" ++
            "zastra_result *" ++ lib ++ "_workflow_start(zastra_app *app, int workflow_id, const char *input_json, zastra_error *err);\n" ++
            "zastra_result *" ++ lib ++ "_workflow_resume(zastra_app *app, const char *run_id, const char *step_id, const char *resume_json, zastra_error *err);\n\n" ++
            "/* Abandon a suspended run of any agent or workflow. */\n" ++
            "zastra_status " ++ lib ++ "_run_cancel(zastra_app *app, const char *run_id, zastra_error *err);\n\n" ++
            "#ifdef __cplusplus\n}\n#endif\n#endif /* " ++ L ++ "_H */\n";
        return h;
    }
}

fn contains(comptime list: []const []const u8, comptime s: []const u8) bool {
    for (list) |x| if (std.mem.eql(u8, x, s)) return true;
    return false;
}
